/** Get structured photo gallery items for a project */
export function getProjectPhotos(project: ProjectItem): ProjectPhotoItem[] {
  if (project.galleryImageObjects && project.galleryImageObjects.length > 0) {
    return project.galleryImageObjects;
  }

  if (project.media && project.media.length > 0) {
    const imagesFromMedia = project.media
      .filter((m) => m.type === 'image')
      .map((m) => ({
        id: m.id,
        src: m.src,
        alt: m.alt || `${project.title} photo`,
        caption: m.caption || IMAGE_CAPTIONS[m.src] || `Protected cultivation view at ${project.title}`,
        title: m.title || project.title,
      }));
    if (imagesFromMedia.length > 0) return imagesFromMedia;
  }

  const rawImages = [
    ...(project.heroImage ? [project.heroImage] : []),
    ...(project.imageUrl && project.imageUrl !== project.heroImage ? [project.imageUrl] : []),
    ...(project.galleryImages || []),
  ];
  const uniqueImages = Array.from(new Set(rawImages));

  return uniqueImages.map((imgUrl, idx) => ({
    id: `${project.id}-photo-${idx + 1}`,
    src: imgUrl,
    alt: `${project.title} site photo ${idx + 1}`,
    title: `${project.title} — Photo ${idx + 1}`,
    caption: IMAGE_CAPTIONS[imgUrl] || `Protected cultivation structure at ${project.title}`,
  }));
}

/** Get structured video items for a project (only real videos) */
export function getProjectVideos(project: ProjectItem): ProjectVideoItem[] {
  if (project.videoObjects && project.videoObjects.length > 0) {
    return project.videoObjects;
  }

  if (project.media && project.media.length > 0) {
    const vidsFromMedia = project.media
      .filter((m) => m.type === 'video')
      .map((m) => ({
        id: m.id,
        src: m.src,
        thumbnail: m.thumbnail || project.heroImage || project.imageUrl || '/gallery/site-gallery-1.jpg',
        title: m.title || `${project.title} — Project Execution Video`,
        caption: m.caption || 'On-site execution & polyhouse installation video',
        videoType: m.videoType || (m.src.includes('youtube') ? 'youtube' : m.src.includes('vimeo') ? 'vimeo' : 'mp4'),
      }));
    if (vidsFromMedia.length > 0) return vidsFromMedia;
  }

  const videoUrls = [
    ...(project.videoUrl && project.videoUrl !== '/hero-banner.mp4' ? [project.videoUrl] : []),
    ...(project.videos || []).filter((v) => v !== '/hero-banner.mp4'),
  ];
  const uniqueVideos = Array.from(new Set(videoUrls));

  return uniqueVideos.map((vUrl, idx) => ({
    id: `${project.id}-video-${idx + 1}`,
    src: vUrl,
    thumbnail: project.heroImage || project.imageUrl || '/gallery/site-gallery-1.jpg',
    title: `${project.title} — Execution Video ${idx + 1}`,
    caption: 'On-site execution, structural setup & agricultural operations video',
    videoType: vUrl.includes('youtube') ? 'youtube' : vUrl.includes('vimeo') ? 'vimeo' : 'mp4',
  }));
}

export function getProjectMediaList(project: ProjectItem) {
  const photos = getProjectPhotos(project).map((p) => ({ ...p, type: 'image' as const }));
  const vids = getProjectVideos(project).map((v) => ({ ...v, type: 'video' as const }));
  return [...photos, ...vids];
}

